/**
 * Helpers for the generated `.px` sources. The letter canvas itself lives in
 * `src/world/art/grid.ts`, because the game draws the hero's layers with it
 * too (W1).
 */

import { Grid } from '../../../../src/world/art/grid';

export { Grid };

/** A `.px` file from named grids of one size. */
export function pxFile(note: string, frames: Array<[string, Grid]>, extra: string[] = []): string {
  const [first] = frames;
  if (!first) throw new Error('no frames');
  const { w, h } = first[1];
  const out = [`# generated by scripts/world/art/generate.ts — ${note}`, `size: ${w}x${h}`];
  for (const [name, g] of frames) {
    if (g.w !== w || g.h !== h) throw new Error(`${name}: ${g.w}x${g.h}, not ${w}x${h}`);
    out.push(`frame: ${name}`, ...g.lines());
  }
  out.push(...extra);
  return out.join('\n') + '\n';
}

/** A deterministic little random, so generated art is the same on every run. */
export function rng(seed: number) {
  let s = seed >>> 0 || 1;
  return () => {
    s ^= s << 13;
    s ^= s >>> 17;
    s ^= s << 5;
    return ((s >>> 0) % 10000) / 10000;
  };
}
