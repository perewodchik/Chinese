"""
What the 214 Kangxi radicals are, written by hand.

No dataset carries this. Make Me a Hanzi says which component of a character is
its radical and hanziDB gives the Kangxi number, but neither knows that 心 is
written three ways, that 阝 is two different radicals depending on the side it
sits on, or that 王 on the left of 玩 means jade. The build used to guess the
written forms by voting among the characters that use each radical, which
produced 贝 as a "variant" of 宀 and 心 as a variant of 八 — and those went on to
gloss 心 as "eight" on every character sheet that showed it as a part.

So each radical is described here once: what it means, what it is called, what
it gets mistaken for, and every distinct way it is written. A written form names
the character its outline is cut from, so the practice squares show it at the
size and position it really has inside a character.

A form earns its own entry when it is written differently, not merely smaller:
忄 and 心 are different shapes, and so is 土 on the left of 地, where the last
stroke rises instead of lying flat. 口 on the left of 吃 is only a smaller 口,
so it is one form.

`scripts/build_radicals.py` checks every entry against the sources and fills in
the counts, the examples and the outlines.
"""
from __future__ import annotations

# Where a form sits in the characters that use it.
ALONE = "alone"
LEFT = "left"
RIGHT = "right"
TOP = "top"
BOTTOM = "bottom"
TOP_LEFT = "topLeft"  # 广 厂 尸 疒: over the top and down the left
BOTTOM_LEFT = "bottomLeft"  # 辶 廴 走: along the bottom and up the left
TOP_RIGHT = "topRight"  # 勹 气: over the top and down the right
AROUND = "around"  # 囗: all the way round

POSITIONS = (ALONE, LEFT, RIGHT, TOP, BOTTOM, TOP_LEFT, BOTTOM_LEFT, TOP_RIGHT, AROUND)


def N(hanzi: str, pinyin: str) -> tuple[str, str]:
    """A colloquial name: 三点水, sān diǎn shuǐ."""
    return (hanzi, pinyin)


def F(g, pos=ALONE, host=None, part=None, name=None, tip=None, ex=None):
    """
    One written form of a radical.

    `host` is the character the outline is cut from, and `part` the component
    as that character's decomposition spells it when that differs from the form
    itself — the ⻊ of 跑 is spelled 足. A form with no host is drawn from its
    own outline, full size: that is what `ALONE` means.

    `ex` replaces the examples the build would otherwise pick, for forms the
    dictionaries file under some other radical (the ⺈ of 负 and 色 is under 贝
    and 色, not 刀).
    """
    return {
        "g": g,
        "pos": pos,
        "host": host,
        "part": part or g,
        "name": name,
        "tip": tip,
        "ex": ex,
    }


def R(mean, py, *, word=None, r=None, about=None, note=None, forms=None, name=None, ex=None):
    """
    One radical.

    `mean` is what it means as a part of other characters, which is not always
    what the character means on its own. `word` is the character the radical is
    named after and `py` its reading — 心 xīn for 忄. `about` says what the
    characters built on it tend to be about; it is left out where the honest
    answer is "nothing in particular". `note` is the look-alike warning.

    A radical with no `forms` is written one way, and that way is `r` (or the
    Kangxi form) on its own; `name` and `ex` then belong to that single form.
    """
    return {
        "mean": mean,
        "py": py,
        "word": word,
        "r": r,
        "about": about,
        "note": note,
        "forms": forms,
        "name": name,
        "ex": ex,
    }


