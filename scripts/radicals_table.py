# Characters that are true to the data but no use as an example: a surname
# (冯), a variant nobody writes (聋), a classical particle (矣), manure (粪).
EXAMPLE_REJECT = set("冯聋矣粪粤鲁叁贰毓氅觯觥")


def shape_glosses(is_character) -> dict[str, str]:
    """
    Meanings for the component shapes that are only ever parts of characters.

    The character sheets gloss every part they list, and for a shape like 氵 or
    扌 the only sensible gloss is the radical's meaning. A shape that is also a
    character in its own right (心, 贝, 户) keeps its own dictionary sense —
    applying the radical's there is exactly how 心 came to be glossed "eight".
    """
    seen: dict[str, list[str]] = {}
    for spec in RADICALS.values():
        glyphs = [f["g"] for f in spec["forms"]] if spec["forms"] else [spec["r"]]
        for g in glyphs:
            if not g or is_character(g):
                continue
            meanings = seen.setdefault(g, [])
            if spec["mean"] not in meanings:
                meanings.append(spec["mean"])
    # 阝 is two radicals: 阜 hill on the left, 邑 city on the right. The sheets
    # know which side a part sits on and say which; the table just has both.
    return {g: " · ".join(m) for g, m in seen.items()}
